// @ts-check
// `pnpm vendor`: copies the fonts the page uses from node_modules into site/vendor/fonts/,
// each with its licence, and gathers the icons it uses (Material Symbols, and brand icons
// from Simple Icons) into site/js/icons.js.
// Run it after changing a font or icon, then `pnpm stamp`.

import { copyFileSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const NM = join(ROOT, 'node_modules');
const FONTS = join(ROOT, 'site/vendor/fonts');

/** Each font: its package, the files to copy, and the folder they go to. */
const fonts = [
  { pkg: '@fontsource-variable/bricolage-grotesque', dir: 'bricolage-grotesque', files: ['bricolage-grotesque-latin-standard-normal.woff2', 'bricolage-grotesque-latin-ext-standard-normal.woff2'] },
  { pkg: '@fontsource-variable/jetbrains-mono', dir: 'jetbrains-mono', files: ['jetbrains-mono-latin-wght-normal.woff2', 'jetbrains-mono-latin-ext-wght-normal.woff2'] },
  { pkg: '@fontsource/caveat-brush', dir: 'caveat-brush', files: ['caveat-brush-latin-400-normal.woff2'] },
  { pkg: '@fontsource/patrick-hand', dir: 'patrick-hand', files: ['patrick-hand-latin-400-normal.woff2'] },
];

/** Material Symbols the page uses, from the rounded set at weight 400 (Apache-2.0). */
const MATERIAL = ['info', 'close', 'arrow_outward', 'play_arrow', 'language'];

/** Brand icons from Simple Icons (CC0-1.0). */
const BRANDS = { github: 'github', x: 'x', zhihu: 'zhihu' };

/**
 * Our own LinkedIn-style "in" glyph: Simple Icons no longer carries LinkedIn's logo, at
 * LinkedIn's request. Holes cut with the even-odd rule.
 */
const OWN = {
  linkedin:
    'M5 2h14a3 3 0 0 1 3 3v14a3 3 0 0 1-3 3H5a3 3 0 0 1-3-3V5a3 3 0 0 1 3-3z' +
    'M7.1 5.4a1.7 1.7 0 1 0 0 3.4a1.7 1.7 0 1 0 0-3.4z' +
    'M5.6 9.8h3v8.8h-3z' +
    'M10.6 9.8h2.9v1.3c.5-.9 1.6-1.6 3-1.6 2.4 0 3 1.6 3 3.8v5.3h-3v-4.7c0-1.1-.3-1.9-1.4-1.9-1.1 0-1.6.8-1.6 1.9v4.7h-2.9z',
};

rmSync(FONTS, { recursive: true, force: true });
for (const f of fonts) {
  mkdirSync(join(FONTS, f.dir), { recursive: true });
  for (const file of [...f.files, 'LICENSE']) copyFileSync(join(NM, f.pkg, file === 'LICENSE' ? 'LICENSE' : `files/${file}`), join(FONTS, f.dir, file));
}

/** @param {string} file */
const pathOf = (file) => {
  const d = readFileSync(file, 'utf8').match(/<path d="([^"]+)"/)?.[1];
  if (!d) throw new Error(`no path in ${file}`);
  return d;
};
/** @type {string[]} */
const lines = [];
for (const name of MATERIAL) lines.push(`  ${name}: { box: '0 -960 960 960', d: '${pathOf(join(NM, '@material-symbols/svg-400/rounded', `${name}.svg`))}' },`);
for (const [name, file] of Object.entries(BRANDS)) lines.push(`  ${name}: { box: '0 0 24 24', d: '${pathOf(join(NM, 'simple-icons/icons', `${file}.svg`))}' },`);
for (const [name, d] of Object.entries(OWN)) lines.push(`  ${name}: { box: '0 0 24 24', d: '${d}', evenodd: true },`);
writeFileSync(
  join(ROOT, 'site/js/icons.js'),
  `// Generated by \`pnpm vendor\` (tools/vendor.mjs). Do not edit. Material Symbols (rounded):
// Apache-2.0, Google LLC. GitHub, X and Zhihu: Simple Icons, CC0-1.0 (the marks belong to
// their owners). The LinkedIn-style glyph is our own.

/** Each icon's path and view box. @type {Record<string, { box: string; d: string; evenodd?: boolean }>} */
export const ICONS = {
${lines.join('\n')}
};

/**
 * An icon as an inline SVG element.
 * @param {string} name
 * @param {number} [size] px
 */
export function icon(name, size = 24) {
  const { box, d, evenodd } = ICONS[name];
  const ns = 'http://www.w3.org/2000/svg';
  const svg = document.createElementNS(ns, 'svg');
  svg.setAttribute('viewBox', box);
  svg.setAttribute('width', String(size));
  svg.setAttribute('height', String(size));
  svg.setAttribute('aria-hidden', 'true');
  svg.setAttribute('class', 'icon');
  const path = document.createElementNS(ns, 'path');
  path.setAttribute('d', d);
  path.setAttribute('fill', 'currentColor');
  if (evenodd) path.setAttribute('fill-rule', 'evenodd');
  svg.append(path);
  return svg;
}
`,
);
const count = MATERIAL.length + Object.keys(BRANDS).length + Object.keys(OWN).length;
process.stdout.write(`Copied ${fonts.length} fonts and ${count} icons.\n`);
