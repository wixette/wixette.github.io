// @ts-check
// `pnpm stamp`: writes each file's content hash into every URL that names it (design D4), so
// that a cache can keep any file for as long as it likes and still never give an old one to
// a new page. Only files that changed get new URLs.
//
//   1. hashes every file the scripts load themselves (images, fonts) into site/js/hashes.js;
//   2. stamps every url() in the stylesheets with its file's hash;
//   3. hashes every JavaScript and CSS file (after 1 and 2, so their hashes cover those);
//   4. stamps every local src/href of site/index.html, and writes its import map, which
//      turns each module's plain URL into its stamped URL.
//
// `pnpm stamp --check` (and tests/stamp.test.js) changes nothing and fails while any stamp is
// stale. index.html itself is never stamped and must not be cached for long.

import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, posix, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

export const SITE = fileURLToPath(new URL('../site', import.meta.url));
const PAGE = 'index.html';
const HASHES_JS = 'js/hashes.js';

/** @param {string | Buffer} data */
export const hashOf = (data) => createHash('sha256').update(data).digest('hex').slice(0, 10);

/**
 * Every file under a folder, as paths relative to it, with forward slashes, sorted.
 * @param {string} root
 * @param {string} [dir]
 * @returns {string[]}
 */
export const walk = (root, dir = '') =>
  readdirSync(join(root, dir), { withFileTypes: true })
    .flatMap((e) => (e.name.startsWith('.') ? [] : e.isDirectory() ? walk(root, posix.join(dir, e.name)) : [posix.join(dir, e.name)]))
    .sort();

/**
 * The generated hashes module.
 * @param {Record<string, string>} hashes
 */
export function hashesModule(hashes) {
  const lines = Object.entries(hashes).map(([k, v]) => `  '${k}': '${v}',`);
  return `// Generated by \`pnpm stamp\` (tools/stamp.mjs): the content hash of every file the scripts
// load at run time, by path from site/. Do not edit.
/** @type {Record<string, string>} */
export const HASHES = {${lines.length ? `\n${lines.join('\n')}\n` : ''}};
`;
}

/**
 * A stylesheet with the hash of each local file its url()s name.
 * @param {string} css
 * @param {string} sheet its path from site/
 * @param {Record<string, string>} hashes by path from site/
 */
export function stampCss(css, sheet, hashes) {
  return css.replace(/url\((["']?)(?![a-z]+:|\/\/|#)([^?#"')]+)(\?v=[^"')]*)?\1\)/gi, (_whole, q, file) => {
    const path = posix.normalize(posix.join(posix.dirname(sheet), file));
    const h = hashes[path];
    if (!h) throw new Error(`${sheet}: url(${file}) names no file`);
    return `url(${q}${file}?v=${h}${q})`;
  });
}

/**
 * The page with the hash of each local file it names, and its import map.
 * @param {string} html
 * @param {Record<string, string>} hashes by path from site/
 */
export function stampPage(html, hashes) {
  const local = /^(?![a-z]+:|\/\/|#)([^?#"]+\.[a-z0-9]+)(\?v=[^"#]*)?$/i;
  let out = html.replace(/\b(src|href)="([^"]*)"/g, (whole, attr, u) => {
    const m = u.match(local);
    if (!m) return whole;
    const h = hashes[posix.normalize(m[1])];
    if (!h) throw new Error(`${PAGE}: ${attr}="${u}" names no file`);
    return `${attr}="${m[1]}?v=${h}"`;
  });
  /** @type {Record<string, string>} */
  const imports = {};
  for (const [path, h] of Object.entries(hashes)) if (path.endsWith('.js')) imports[`./${path}`] = `./${path}?v=${h}`;
  const json = JSON.stringify({ imports }, null, 2).replace(/\n/g, '\n    ');
  const block = /(<script type="importmap">\n    )[\s\S]*?(\n    <\/script>)/;
  if (!block.test(out)) throw new Error(`${PAGE} has no import map to stamp`);
  out = out.replace(block, (_w, open, close) => open + json + close);
  return out;
}

/**
 * Computes every stamped file. Returns the files whose content would change.
 * @param {{ write: boolean; root?: string }} o
 * @returns {string[]}
 */
export function stampAll({ write, root = SITE }) {
  /** @type {Map<string, string>} the new contents of the files that change */
  const changes = new Map();
  const read = (/** @type {string} */ p) => changes.get(p) ?? readFileSync(join(root, p), 'utf8');
  const files = walk(root);
  const isCode = (/** @type {string} */ p) => p.endsWith('.js') || p.endsWith('.css') || p.endsWith('.html');

  /** @type {Record<string, string>} */
  const hashes = {};
  for (const p of files) if (!isCode(p)) hashes[p] = hashOf(readFileSync(join(root, p)));
  /** @type {Record<string, string>} */
  const runtime = {};
  for (const [p, h] of Object.entries(hashes)) if (!p.startsWith('vendor/fonts/') && !p.endsWith('LICENSE')) runtime[p] = h;
  const module = hashesModule(runtime);
  if (module !== read(HASHES_JS)) changes.set(HASHES_JS, module);

  for (const p of files.filter((f) => f.endsWith('.css'))) {
    const css = stampCss(read(p), p, hashes);
    if (css !== read(p)) changes.set(p, css);
  }
  for (const p of files.filter((f) => f.endsWith('.js') || f.endsWith('.css'))) hashes[p] = hashOf(read(p));
  const page = stampPage(read(PAGE), hashes);
  if (page !== read(PAGE)) changes.set(PAGE, page);

  if (write) for (const [p, content] of changes) writeFileSync(join(root, p), content);
  return [...changes.keys()];
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const changed = stampAll({ write: !check });
  const where = relative(process.cwd(), SITE) || '.';
  if (check && changed.length) {
    process.stderr.write(`Stale stamps in ${changed.map((p) => join(where, p)).join(', ')}: run pnpm stamp.\n`);
    process.exit(1);
  }
  process.stdout.write(changed.length ? `Stamped ${changed.map((p) => join(where, p)).join(', ')}.\n` : 'Every stamp is up to date.\n');
}

